#!/usr/bin/env python3
"""Write site/explain/pathway_steps.js from danaSeq's bundled KEGG module definitions.

danaSeq (mag_analysis/bin/kegg_module_completeness.py) scores a module as the fraction of its
steps with at least one KO present. This copies those same steps, in order, with the gene
names from the source comments, so the Function tab can draw one box per step.
    make_pathway_steps.py <danaSeq>/mag_analysis/bin/kegg_module_completeness.py [out.js]
"""
import ast, json, os, sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "../../site/explain/pathway_steps.js")
text = open(src).read()
lines = text.splitlines()
tree = ast.parse(text)

mods = None
for node in tree.body:
    if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "KEGG_MODULES":
        mods = node.value
if mods is None:
    sys.exit(f"[ERROR] no KEGG_MODULES dict in {src}")


def comment(lineno):
    line = lines[lineno - 1]
    return line.split("#", 1)[1].strip() if "#" in line else ""


res = {}
for k, v in zip(mods.keys, mods.values):
    mid = ast.literal_eval(k)
    name, cat, steps = v.elts
    res[mid] = {
        "name": ast.literal_eval(name),
        "category": ast.literal_eval(cat),
        "steps": [{"kos": sorted(ast.literal_eval(s)), "genes": comment(s.lineno)} for s in steps.elts],
    }

os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    f.write("// Generated by scripts/build/make_pathway_steps.py from danaSeq kegg_module_completeness.py.\n"
            "// KEGG module id -> {name, category, steps: [{kos: alternative KOs, genes: gene names}]}, in pathway order.\n"
            "window.PATHWAY_STEPS = ")
    f.write("{\n" + ",\n".join(f" {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in res.items()) + "\n};\n")
print(f"[INFO] {len(res)} modules -> {out}")
